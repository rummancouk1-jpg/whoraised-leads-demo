import fs from 'node:fs/promises';
import {chromium,expect} from '@playwright/test';
import {login,logout,cookieParts,activityFixture} from '../design/lib.mjs';
const origin='http://localhost:3103',dir='evidence/r2-independent',rows=[];
const leads=JSON.parse(await fs.readFile(dir+'/leads.json','utf8'));
const cookie=await login(origin),browser=await chromium.launch({channel:'chrome'});
const c=await browser.newContext({viewport:{width:390,height:844},serviceWorkers:'block'});
await c.addCookies([{...cookieParts(cookie),url:origin,httpOnly:true,secure:true,sameSite:'Lax'}]);
const page=await c.newPage();let failed=false;
let fx=activityFixture('busy',leads);fx.queue=[];
await c.route('**/api/sync**',r=>r.fulfill({status:503,json:{error:'sync unavailable'}}));
await c.route('**/api/errors',r=>r.fulfill({json:{ok:true}}));
await c.route('**/api/activity',r=>failed?r.fulfill({status:503,json:{error:'database unavailable'}}):r.fulfill({json:fx}));
await page.goto(origin+'/');await expect(page.locator('.gg-needs-empty')).toContainText("You're clear");
failed=true;
await page.evaluate(()=>document.dispatchEvent(new Event('visibilitychange')));
await page.waitForResponse(r=>r.url().endsWith('/api/activity')&&r.status()===503);
await page.waitForTimeout(200);
rows.push({case:'previous good activity read, then endpoint 503',queue:await page.locator('.gg-needs-empty').innerText(),bannerCount:await page.locator('.gg-sync-banner').count(),freshness:await page.locator('.gg-needs .gg-fresh').innerText()});
await page.screenshot({path:dir+'/screenshots/failure-cached-clear.png'});
// Advance the browser clock without another successful activity response. Existing sync state remains "ok".
await page.clock.install({time:Date.now()});const timeBefore=await page.evaluate(()=>Date.now());await page.clock.fastForward(45*60000);await page.waitForTimeout(300);
rows.push({case:'45 minutes without a successful activity read',clockAdvancedMinutes:(await page.evaluate(()=>Date.now())-timeBefore)/60000,queue:await page.locator('.gg-needs-empty').innerText(),bannerCount:await page.locator('.gg-sync-banner').count(),pill:await page.locator('.gg-sync-pill').innerText()});
await page.screenshot({path:dir+'/screenshots/failure-45min-no-warning.png'});
await c.route('**/api/digest',r=>r.fulfill({status:503,json:{error:'slow DB'}}));
await page.goto(origin+'/email');await expect(page.locator('section:has(#digest-title) [role=alert]')).toBeVisible();
rows.push({case:'digest endpoint 503',copy:await page.locator('section:has(#digest-title) [role=alert]').innerText(),buttons:await page.locator('section:has(#digest-title) button').count()});
await page.screenshot({path:dir+'/screenshots/failure-digest-no-retry.png'});
await c.close();await browser.close();await logout(origin,cookie);
await fs.writeFile(dir+'/failure-ux.json',JSON.stringify(rows,null,2));console.log(JSON.stringify(rows,null,2));
